// reportManifest is the committed list of curated report cases. It holds ids
// only: names, notes, instructions and report text stay local.
type reportManifest struct {
	Reports []reportManifestEntry `json:"reports"`
}

// A fresh case's reference lives in the reference store under its id. A
// regenerate case names the DB report the Teacher revised and its feedback
// rows, one per round, oldest first. A tweak case rewrites one paragraph of
// a fresh case's reference. Expect holds extra rubric lines, name-free like
// the description.
type reportManifestEntry struct {
	ID          string       `json:"id"`
	Description string       `json:"description"`
	StudentID   int64        `json:"student_id"`
	ReportID    int64        `json:"report_id,omitempty"`
	Feedback    []int64      `json:"feedback,omitempty"`
	Tweak       *reportTweak `json:"tweak,omitempty"`
	Expect      []string     `json:"expect,omitempty"`
}

// reportTweak is a paragraph tweak of fresh case Of's reference. Ask is
// written in the manifest, so name-free. Chars bounds the paragraph's text
// length when the ask sets one. StripLevelExamples removes the quoted example
// sentences from the Level text: a Level with nothing stock to pad from.
type reportTweak struct {
	Of                 string `json:"of"`
	Paragraph          int    `json:"paragraph"`
	Ask                string `json:"ask"`
	Chars              []int  `json:"chars,omitempty"`
	StripLevelExamples bool   `json:"strip_level_examples,omitempty"`
}

// caseIDPattern keeps ids safe as directory names.
var caseIDPattern = regexp.MustCompile(`^[a-z0-9_-]+$`)

type reportTest struct {
	Description string         `yaml:"description"`
	Vars        reportTestVars `yaml:"vars"`
	// Prompts keeps regenerate cases off the gold-reference row: it echoes the
	// draft, which ignores the feedback.
	Prompts []string `yaml:"prompts,omitempty"`
	// Set on tweak cases: the default axes grade a whole report, and a tweak
	// outputs one paragraph.
	Options *reportTestOptions `yaml:"options,omitempty"`
	Assert  []reportAssert     `yaml:"assert,omitempty"`
}

type reportTestVars struct {
	StudentName        string `yaml:"student_name"`
	ClassName          string `yaml:"class_name"`
	Notes              string `yaml:"notes"`
	ReportInstructions string `yaml:"report_instructions"`
	Instructions       string `yaml:"instructions"`
	Reference          string `yaml:"reference"`
	Draft              string `yaml:"draft,omitempty"`
	DraftCreatedAt     string `yaml:"draft_created_at,omitempty"`
	Feedback           string `yaml:"feedback,omitempty"`
	Paragraph          *int   `yaml:"paragraph,omitempty"`
}

type reportTestOptions struct {
	DisableDefaultAsserts bool `yaml:"disableDefaultAsserts"`
}

type reportAssert struct {
	Type      string  `yaml:"type"`
	Metric    string  `yaml:"metric"`
	Threshold float64 `yaml:"threshold,omitempty"`
	Value     string  `yaml:"value"`
}

// reportNote is the note shape the prompt and the judge read; other Note
// fields (transcript, ids) would only bloat the judge prompt. UpdatedAt is set
// on notes changed since a regenerate case's draft only: the prompt tags them.
type reportNote struct {
	Date      string `json:"date"`
	Summary   string `json:"summary"`
	UpdatedAt string `json:"updatedAt,omitempty"`
}

// gradedPrompt is the report config's model prompt; regenerate cases run on
// it alone.
const gradedPrompt = "gradebee-prompt"

const generatedHeader = "# Generated by `eval-cli gen-report-cases` from the local DB and reference store. Do not edit; run `make eval-fixtures`.\n"

func runGenReportCases(args []string) error {
	fs := flag.NewFlagSet("gen-report-cases", flag.ContinueOnError)
	dbPath := fs.String("db", "", "SQLite DB to read cases from")
	refsDir := fs.String("refs", "", "reference store holding fresh cases' references")
	manifestPath := fs.String("manifest", "", "report case manifest (JSON)")
	casesDir := fs.String("cases-dir", "", "directory to write case files into; replaced on every run")
	testsPath := fs.String("tests", "", "promptfoo test list to write (YAML)")
	if err := fs.Parse(args); err != nil {
		return err
	}
	if *dbPath == "" || *refsDir == "" || *manifestPath == "" || *casesDir == "" || *testsPath == "" {
		return fmt.Errorf("usage: eval-cli gen-report-cases -db PATH -refs DIR -manifest PATH -cases-dir DIR -tests PATH")
	}

	manifest, err := readReportManifest(*manifestPath)
	if err != nil {
		return err
	}
	cases, err := loadReportCases(*dbPath, *refsDir, manifest)
	if err != nil {
		return err
	}
	return writeReportCases(manifest, cases, *casesDir, *testsPath)
}

func readReportManifest(path string) (reportManifest, error) {
	raw, err := os.ReadFile(path)
	if err != nil {
		return reportManifest{}, fmt.Errorf("read manifest: %w", err)
	}
	var m reportManifest
	if err := json.Unmarshal(raw, &m); err != nil {
		return reportManifest{}, fmt.Errorf("parse manifest %s: %w", path, err)
	}
	if len(m.Reports) == 0 {
		return reportManifest{}, fmt.Errorf("manifest %s lists no report cases", path)
	}
	seen := map[string]bool{}
	for i, e := range m.Reports {
		switch {
		case !caseIDPattern.MatchString(e.ID):
			return reportManifest{}, fmt.Errorf("manifest entry %d: id %q must match %s", i, e.ID, caseIDPattern)
		case seen[e.ID]:
			return reportManifest{}, fmt.Errorf("manifest entry %d: duplicate id %q", i, e.ID)
		case e.Description == "":
			return reportManifest{}, fmt.Errorf("case %q: description is required", e.ID)
		case e.StudentID <= 0:
			return reportManifest{}, fmt.Errorf("case %q: student_id is required", e.ID)
		case len(e.Feedback) > 0 && e.ReportID <= 0:
			return reportManifest{}, fmt.Errorf("case %q: a regenerate case needs report_id, the draft", e.ID)
		case len(e.Feedback) == 0 && e.ReportID != 0:
			return reportManifest{}, fmt.Errorf("case %q: a fresh case takes its reference from the store by id, not report_id", e.ID)
		case e.Tweak != nil && (len(e.Feedback) > 0 || e.Tweak.Of == "" || strings.TrimSpace(e.Tweak.Ask) == ""):
			return reportManifest{}, fmt.Errorf("case %q: a tweak case needs of and ask, and no feedback ids", e.ID)
		case e.Tweak != nil && len(e.Tweak.Chars) != 0 && len(e.Tweak.Chars) != 2:
			return reportManifest{}, fmt.Errorf("case %q: tweak chars is [min, max]", e.ID)
		}
		seen[e.ID] = true
	}
	return m, nil
}

// reportCase is what report generation feeds BuildReportPrompt, plus the
// reference HTML the judge reads: for a regenerate case, the draft the Teacher
// revised.
type reportCase struct {
	handler.ReportInputs
	ReferenceHTML string
	// Regenerate cases only: feedback comments oldest first, the notes added
	// or edited since the draft, and the draft's created_at.
	Feedback       []string
	ChangedNotes   []handler.Note
	DraftCreatedAt string
	// Tweak cases only: the paragraph's text, for the judge.
	ParagraphText string
}

// loadReportCases reads every case, then closes the DB before anything is
// written: make compares the test list's mtime against the DB's, and a close
// that checkpoints the WAL afterwards would mark the output stale.
func loadReportCases(dbPath, refsDir string, m reportManifest) ([]reportCase, error) {
	if _, err := os.Stat(dbPath); err != nil {
		return nil, fmt.Errorf("db: %w", err)
	}
	db, err := handler.OpenDB(dbPath)
	if err != nil {
		return nil, err
	}
	defer db.Close()
	ctx := context.Background()
	resolver := handler.NewReportInputResolver(db)
	cases := make([]reportCase, 0, len(m.Reports))
	for _, e := range m.Reports {
		var c reportCase
		var err error
		switch {
		case e.Tweak != nil:
			c, err = loadTweakCase(ctx, resolver, refsDir, e)
		case len(e.Feedback) == 0:
			c, err = loadFreshCase(ctx, resolver, refsDir, e)
		default:
			c, err = loadRegenerateCase(ctx, db, resolver, e)
		}
		if err != nil {
			return nil, fmt.Errorf("case %q: %w", e.ID, err)
		}
		cases = append(cases, c)
	}
	return cases, nil
}

// loadFreshCase resolves the reference's range and ad-hoc instructions
// through the resolver Generate uses, then refuses notes that differ from
// those the reference was written from.
func loadFreshCase(ctx context.Context, resolver *handler.ReportInputResolver, refsDir string, e reportManifestEntry) (reportCase, error) {
	meta, html, err := readReference(refsDir, e.ID)
	if err != nil {
		return reportCase{}, err
	}
	if meta.StudentID != e.StudentID {
		return reportCase{}, fmt.Errorf("reference is for student %d, not student %d", meta.StudentID, e.StudentID)
	}
	in, err := resolver.ForGenerate(ctx, "", handler.ReportStudentInput{StudentID: e.StudentID}, meta.StartDate, meta.EndDate, meta.Instructions)
	if err != nil {
		return reportCase{}, err
	}
	if err := checkReferenceNotes(meta.Notes, in.Notes); err != nil {
		return reportCase{}, err
	}
	if len(in.Notes) == 0 {
		return reportCase{}, fmt.Errorf("student %d has no notes between %s and %s", e.StudentID, meta.StartDate, meta.EndDate)
	}
	return reportCase{ReportInputs: in, ReferenceHTML: html}, nil
}

var levelExample = regexp.MustCompile(`"[^"\n]{8,}"|“[^”\n]{8,}”`)

// loadTweakCase takes the base case's inputs and reference as the draft.
func loadTweakCase(ctx context.Context, resolver *handler.ReportInputResolver, refsDir string, e reportManifestEntry) (reportCase, error) {
	tw := e.Tweak
	c, err := loadFreshCase(ctx, resolver, refsDir, reportManifestEntry{ID: tw.Of, StudentID: e.StudentID})
	if err != nil {
		return reportCase{}, fmt.Errorf("tweak of %q: %w", tw.Of, err)
	}
	paragraph, err := handler.ReportParagraph(c.ReferenceHTML, tw.Paragraph)
	if err != nil {
		return reportCase{}, fmt.Errorf("tweak paragraph %d: %w", tw.Paragraph, err)
	}
	if tw.StripLevelExamples {
		c.ReportInstructions = levelExample.ReplaceAllString(c.ReportInstructions, "")
	}
	c.Feedback = []string{tw.Ask}
	c.ParagraphText = handler.ParagraphText(paragraph)
	return c, nil
}

// loadRegenerateCase feeds today's notes, as regenerate does: notes changed
// since the draft are the Teacher's corrections, not staleness.
func loadRegenerateCase(ctx context.Context, db *sql.DB, resolver *handler.ReportInputResolver, e reportManifestEntry) (reportCase, error) {
	in, rpt, err := resolver.ForReport(ctx, "", e.StudentID, e.ReportID)
	if err != nil {
		return reportCase{}, err
	}
	if len(in.Notes) == 0 {
		return reportCase{}, errNoNotes(in, rpt)
	}
	changed, err := notesChangedSince(in, rpt)
	if err != nil {
		return reportCase{}, err
	}
	feedback := make([]string, len(e.Feedback))
	for i, id := range e.Feedback {
		if feedback[i], err = loadFeedbackComment(ctx, db, e.StudentID, id); err != nil {
			return reportCase{}, err
		}
	}
	return reportCase{ReportInputs: in, ReferenceHTML: rpt.HTML, Feedback: feedback, ChangedNotes: changed, DraftCreatedAt: rpt.CreatedAt}, nil
}

// loadFeedbackComment returns a feedback row's comment, refusing a row on
// another student's report or with no comment to act on.
func loadFeedbackComment(ctx context.Context, db *sql.DB, studentID, feedbackID int64) (string, error) {
	var owner int64
	var comment string
	err := db.QueryRowContext(ctx, `
		SELECT r.student_id, COALESCE(f.comment, '')
		FROM artifact_feedback f
		JOIN reports r ON r.id = f.artifact_id
		WHERE f.id = ? AND f.artifact_type = 'report'`, feedbackID).Scan(&owner, &comment)
	if errors.Is(err, sql.ErrNoRows) {
		return "", fmt.Errorf("feedback %d: no feedback on a report with that id", feedbackID)
	}
	if err != nil {
		return "", fmt.Errorf("feedback %d: %w", feedbackID, err)
	}
	if owner != studentID {
		return "", fmt.Errorf("feedback %d is on a report of student %d, not student %d", feedbackID, owner, studentID)
	}
	if strings.TrimSpace(comment) == "" {
		return "", fmt.Errorf("feedback %d has no comment", feedbackID)
	}
	return comment, nil
}

func errNoNotes(in handler.ReportInputs, rpt handler.Report) error {
	return fmt.Errorf("report %d: student %d has no notes between %s and %s", rpt.ID, in.StudentID, in.StartDate, in.EndDate)
}

// notesChangedSince returns the notes created or edited after the report.
func notesChangedSince(in handler.ReportInputs, rpt handler.Report) ([]handler.Note, error) {
	generated, err := time.Parse(time.RFC3339Nano, rpt.CreatedAt)
	if err != nil {
		return nil, fmt.Errorf("report %d created_at: %w", rpt.ID, err)
	}
	var changed []handler.Note
	for _, n := range in.Notes {
		for _, ts := range []string{n.CreatedAt, n.UpdatedAt} {
			t, err := time.Parse(time.RFC3339Nano, ts)
			if err != nil {
				return nil, fmt.Errorf("note %d: %w", n.ID, err)
			}
			if t.After(generated) {
				changed = append(changed, n)
				break
			}
		}
	}
	return changed, nil
}

func writeReportCases(m reportManifest, cases []reportCase, casesDir, testsPath string) error {
	if err := os.RemoveAll(casesDir); err != nil {
		return fmt.Errorf("clear %s: %w", casesDir, err)
	}
	relDir, err := filepath.Rel(filepath.Dir(testsPath), casesDir)
	if err != nil {
		return fmt.Errorf("cases dir relative to tests: %w", err)
	}
	tests := make([]reportTest, 0, len(cases))
	for i, e := range m.Reports {
		c := cases[i]
		dir := filepath.Join(casesDir, e.ID)
		if err := os.MkdirAll(dir, 0o755); err != nil {
			return err
		}
		changed := map[int64]bool{}
		for _, n := range c.ChangedNotes {
			changed[n.ID] = true
		}
		notes := make([]reportNote, len(c.Notes))
		for j, n := range c.Notes {
			notes[j] = reportNote{Date: n.Date, Summary: n.Summary}
			if changed[n.ID] {
				notes[j].UpdatedAt = n.UpdatedAt
			}
		}
		notesJSON, err := json.MarshalIndent(notes, "", "  ")
		if err != nil {
			return err
		}
		files := map[string][]byte{
			"notes.json":              notesJSON,
			"report_instructions.txt": []byte(c.ReportInstructions),
			"instructions.txt":        []byte(c.Instructions),
			"reference.html":          []byte(c.ReferenceHTML),
		}
		if len(c.Feedback) > 0 {
			if files["feedback.json"], err = json.MarshalIndent(c.Feedback, "", "  "); err != nil {
				return err
			}
		}
		for name, content := range files {
			if err := os.WriteFile(filepath.Join(dir, name), content, 0o644); err != nil {
				return err
			}
		}
		ref := func(name string) string {
			return "file://" + filepath.ToSlash(filepath.Join(relDir, e.ID, name))
		}
		t := reportTest{
			Description: "report: " + e.Description,
			Vars: reportTestVars{
				StudentName:        c.StudentName,
				ClassName:          c.ClassName,
				Notes:              ref("notes.json"),
				ReportInstructions: ref("report_instructions.txt"),
				Instructions:       ref("instructions.txt"),
				Reference:          ref("reference.html"),
			},
		}
		switch {
		case e.Tweak != nil:
			t.Vars.Draft = ref("reference.html")
			t.Vars.Feedback = ref("feedback.json")
			t.Vars.Paragraph = &e.Tweak.Paragraph
			t.Prompts = []string{gradedPrompt}
			t.Options = &reportTestOptions{DisableDefaultAsserts: true}
			t.Assert = tweakAsserts(c, *e.Tweak, e.Expect)
		case len(c.Feedback) > 0:
			t.Vars.Draft = ref("reference.html")
			t.Vars.DraftCreatedAt = c.DraftCreatedAt
			t.Vars.Feedback = ref("feedback.json")
			t.Prompts = []string{gradedPrompt}
			t.Assert = regenerateAsserts(c, e.Expect)
		default:
			t.Assert = expectAsserts("the output is a fresh report written from the notes", e.Expect)
		}
		tests = append(tests, t)
	}
	out, err := yaml.Marshal(tests)
	if err != nil {
		return err
	}
	if err := os.WriteFile(testsPath, append([]byte(generatedHeader), out...), 0o644); err != nil {
		return fmt.Errorf("write tests: %w", err)
	}
	return nil
}

// regenerateAsserts grades a regenerate case beyond the shared axes: each
// feedback round applied, the rest of the draft kept, notes changed since the
// draft used, and the manifest's expect lines. The judge reads the draft as
// its reference report. No word-count transform: promptfoo inlines file:// in
// an external tests file, so the transform would arrive as source text, and
// these lines judge no length. promptfoo renders rubric values as nunjucks: a
// feedback or note holding "{{" or "{%" would break its line at eval time.
func regenerateAsserts(c reportCase, expect []string) []reportAssert {
	rubric := func(metric, value string) reportAssert {
		return reportAssert{Type: "llm-rubric", Metric: metric, Threshold: 0.75, Value: value}
	}
	const draftIs = "here the reference report is not an accepted report: it is the draft the Teacher asked to revise"
	var list strings.Builder
	for i, fb := range c.Feedback {
		fmt.Fprintf(&list, "%d. %q\n", i+1, fb)
	}
	var out []reportAssert
	for i, fb := range c.Feedback {
		out = append(out, rubric("feedback", fmt.Sprintf(`feedback: %s, in %d rounds of feedback, oldest first; each round revised the previous round's output.
Round %d asked: %q
The output does what round %d asked. A later round overrides it only where the two conflict.
5: done in full
4: done, one small leftover
3: half done, or done then partly undone
2: barely done
1: ignored or undone
`, draftIs, len(c.Feedback), i+1, fb, i+1)))
	}
	// Counted, not holistic: the holistic line swung 0.5-1 on one output
	// whether a softened difficulty lost its harsh details (task 220).
	out = append(out, rubric("kept", fmt.Sprintf(`kept: %s. The feedback, oldest first:
%sCount lost facts:
1. List each fact of the draft in one short line.
2. A fact no feedback asks to change is kept when the output still states it, reworded at most.
3. A fact the feedback asks to soften, reword or make more positive is kept when the output still names the difficulty or topic, in general words if need be. Its specific details (an action, an example, a frequency) may go.
4. A fact the feedback asks to remove is never lost.
5. A fact left out is not lost when the output meets a length the feedback or the Report Specification sets.
Facts from the notes that the draft lacked may be added. In your reason, name each lost fact, or say none.
5: no fact lost
4: one fact lost
3: two facts lost
2: three or four facts lost
1: five or more lost, or rewritten from scratch
`, draftIs, list.String())))
	if len(c.ChangedNotes) > 0 {
		var notes strings.Builder
		for _, n := range c.ChangedNotes {
			fmt.Fprintf(&notes, "- %s: %s\n", n.Date, n.Summary)
		}
		out = append(out, rubric("new-notes", fmt.Sprintf(`new-notes: %s. The Teacher added or edited these notes after the draft; the output uses their facts, even where the draft said otherwise. A fact left out is no miss when the output meets a length the feedback or the Report Specification sets:
%s5: every fact used
4: one minor fact missed
3: some facts used
2: one fact barely used
1: none used, or the draft's old version kept
`, draftIs, notes.String())))
	}
	return append(out, expectAsserts(draftIs, expect)...)
}

// tweakAsserts grades a paragraph tweak's output, the paragraph alone: one
// paragraph with no placeholder left, the length the ask set, the ask done,
// nothing claimed about the student beyond the notes. Braces and % go from the
// quoted paragraph: promptfoo renders rubric values as nunjucks.
func tweakAsserts(c reportCase, tw reportTweak, expect []string) []reportAssert {
	rubric := func(metric, value string) reportAssert {
		return reportAssert{Type: "llm-rubric", Metric: metric, Threshold: 0.75, Value: value}
	}
	quoted := strings.NewReplacer("{", "", "}", "", "%", "").Replace(c.ParagraphText)
	// Mirrors the server's refusal: block tags inside the unwrapped answer.
	out := []reportAssert{{Type: "javascript", Metric: "one-paragraph",
		Value: `!/<\/?(p|li|ul|ol|h[1-6]|div|table)\b/i.test(output.trim().replace(/^<(p|li)\b[^>]*>([\s\S]*)<\/\1>$/, '$2'))`}}
	if len(tw.Chars) == 2 {
		out = append(out, reportAssert{Type: "javascript", Metric: "length", Value: fmt.Sprintf(
			`(t => !t.includes('[MISSING') && t.length >= %d && t.length <= %d)(output.replace(/<[^>]+>/g, '').replace(/\s+/g, ' ').trim())`,
			tw.Chars[0], tw.Chars[1])})
	}
	out = append(out,
		rubric("tweak", fmt.Sprintf(`tweak: the output is one paragraph of a report card, rewritten from this one: %q. The Teacher asked: %q. The ask overrides the Report Specification's length, placeholder and padding rules.
5: the ask done in full, the paragraph's facts kept, no placeholder left
4: done, length a little off
3: placeholder gone but the ask half done, or placeholder kept beside new text
2: barely changed
1: unchanged, or not a single paragraph
`, quoted, tw.Ask)),
		rubric("no-invention", fmt.Sprintf(`no-invention: the output is one rewritten paragraph of a report card. Sort every sentence it adds to the original paragraph (%q): (a) a fact from the notes below; (b) a sentence or phrase the Report Specification below offers, near verbatim; (c) a statement true of any student in this class (the class's activities, the course's aims) that says nothing about this student in particular; (d) a claim about this student (behaviour, liking, skill, progress, feeling, event) the notes do not support. Name each (d) sentence in your reason, and count (a), (b), (c), (d).
Report Specification:
{{report_instructions}}
Notes:
{{notes}}
5: no (d)
3: one (d), mild
1: one clear (d) or several
`, quoted)))
	return append(out, expectAsserts("the output is one paragraph a Teacher asked to rewrite", expect)...)
}

// expectAsserts turns the manifest's expect lines into rubric lines; context
// tells the judge what the output is.
func expectAsserts(context string, expect []string) []reportAssert {
	var out []reportAssert
	for _, x := range expect {
		out = append(out, reportAssert{Type: "llm-rubric", Metric: "expect", Threshold: 0.75, Value: fmt.Sprintf(`expect: %s.
%s
5: holds in full
4: holds, one slip
3: half holds
2: barely holds
1: fails
`, context, x)})
	}
	return out
}
