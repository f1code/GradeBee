package main

import (
	"context"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"regexp"

	"gopkg.in/yaml.v3"

	handler "github.com/nicogaller/gradebee/backend"
)

// reportManifest is the committed list of curated report cases. It holds ids
// only: names, notes, instructions and report text stay in the local DB.
type reportManifest struct {
	Reports []reportManifestEntry `json:"reports"`
}

type reportManifestEntry struct {
	ID          string `json:"id"`
	Description string `json:"description"`
	StudentID   int64  `json:"student_id"`
	ReportID    int64  `json:"report_id"`
}

// caseIDPattern keeps ids safe as directory names.
var caseIDPattern = regexp.MustCompile(`^[a-z0-9_-]+$`)

type reportTest struct {
	Description string         `yaml:"description"`
	Vars        reportTestVars `yaml:"vars"`
}

type reportTestVars struct {
	StudentName        string `yaml:"student_name"`
	ClassName          string `yaml:"class_name"`
	Notes              string `yaml:"notes"`
	ReportInstructions string `yaml:"report_instructions"`
	Instructions       string `yaml:"instructions"`
	Reference          string `yaml:"reference"`
}

// reportNote is the note shape the prompt and the judge read; other Note
// fields (transcript, ids) would only bloat the judge prompt.
type reportNote struct {
	Date    string `json:"date"`
	Summary string `json:"summary"`
}

const generatedHeader = "# Generated by `eval-cli gen-report-cases` from the local DB. Do not edit; run `make eval-fixtures`.\n"

func runGenReportCases(args []string) error {
	fs := flag.NewFlagSet("gen-report-cases", flag.ContinueOnError)
	dbPath := fs.String("db", "", "SQLite DB to read cases from")
	manifestPath := fs.String("manifest", "", "report case manifest (JSON)")
	casesDir := fs.String("cases-dir", "", "directory to write case files into; replaced on every run")
	testsPath := fs.String("tests", "", "promptfoo test list to write (YAML)")
	if err := fs.Parse(args); err != nil {
		return err
	}
	if *dbPath == "" || *manifestPath == "" || *casesDir == "" || *testsPath == "" {
		return fmt.Errorf("usage: eval-cli gen-report-cases -db PATH -manifest PATH -cases-dir DIR -tests PATH")
	}

	manifest, err := readReportManifest(*manifestPath)
	if err != nil {
		return err
	}
	cases, err := loadReportCases(*dbPath, manifest)
	if err != nil {
		return err
	}
	return writeReportCases(manifest, cases, *casesDir, *testsPath)
}

func readReportManifest(path string) (reportManifest, error) {
	raw, err := os.ReadFile(path)
	if err != nil {
		return reportManifest{}, fmt.Errorf("read manifest: %w", err)
	}
	var m reportManifest
	if err := json.Unmarshal(raw, &m); err != nil {
		return reportManifest{}, fmt.Errorf("parse manifest %s: %w", path, err)
	}
	if len(m.Reports) == 0 {
		return reportManifest{}, fmt.Errorf("manifest %s lists no report cases", path)
	}
	seen := map[string]bool{}
	for i, e := range m.Reports {
		switch {
		case !caseIDPattern.MatchString(e.ID):
			return reportManifest{}, fmt.Errorf("manifest entry %d: id %q must match %s", i, e.ID, caseIDPattern)
		case seen[e.ID]:
			return reportManifest{}, fmt.Errorf("manifest entry %d: duplicate id %q", i, e.ID)
		case e.Description == "":
			return reportManifest{}, fmt.Errorf("case %q: description is required", e.ID)
		case e.StudentID <= 0 || e.ReportID <= 0:
			return reportManifest{}, fmt.Errorf("case %q: student_id and report_id are required", e.ID)
		}
		seen[e.ID] = true
	}
	return m, nil
}

// loadReportCases reads every case, then closes the DB before anything is
// written: make compares the test list's mtime against the DB's, and a close
// that checkpoints the WAL afterwards would mark the output stale.
func loadReportCases(dbPath string, m reportManifest) ([]handler.ReportEvalCase, error) {
	if _, err := os.Stat(dbPath); err != nil {
		return nil, fmt.Errorf("db: %w", err)
	}
	db, err := handler.OpenDB(dbPath)
	if err != nil {
		return nil, err
	}
	defer db.Close()
	cases := make([]handler.ReportEvalCase, 0, len(m.Reports))
	for _, e := range m.Reports {
		c, err := handler.LoadReportEvalCase(context.Background(), db, e.StudentID, e.ReportID)
		if err != nil {
			return nil, fmt.Errorf("case %q: %w", e.ID, err)
		}
		cases = append(cases, c)
	}
	return cases, nil
}

func writeReportCases(m reportManifest, cases []handler.ReportEvalCase, casesDir, testsPath string) error {
	if err := os.RemoveAll(casesDir); err != nil {
		return fmt.Errorf("clear %s: %w", casesDir, err)
	}
	relDir, err := filepath.Rel(filepath.Dir(testsPath), casesDir)
	if err != nil {
		return fmt.Errorf("cases dir relative to tests: %w", err)
	}
	tests := make([]reportTest, 0, len(cases))
	for i, e := range m.Reports {
		c := cases[i]
		dir := filepath.Join(casesDir, e.ID)
		if err := os.MkdirAll(dir, 0o755); err != nil {
			return err
		}
		notes := make([]reportNote, len(c.Notes))
		for j, n := range c.Notes {
			notes[j] = reportNote{Date: n.Date, Summary: n.Summary}
		}
		notesJSON, err := json.MarshalIndent(notes, "", "  ")
		if err != nil {
			return err
		}
		files := map[string][]byte{
			"notes.json":              notesJSON,
			"report_instructions.txt": []byte(c.ReportInstructions),
			"instructions.txt":        []byte(c.Instructions),
			"reference.html":          []byte(c.ReferenceHTML),
		}
		for name, content := range files {
			if err := os.WriteFile(filepath.Join(dir, name), content, 0o644); err != nil {
				return err
			}
		}
		ref := func(name string) string {
			return "file://" + filepath.ToSlash(filepath.Join(relDir, e.ID, name))
		}
		tests = append(tests, reportTest{
			Description: "report: " + e.Description,
			Vars: reportTestVars{
				StudentName:        c.StudentName,
				ClassName:          c.ClassName,
				Notes:              ref("notes.json"),
				ReportInstructions: ref("report_instructions.txt"),
				Instructions:       ref("instructions.txt"),
				Reference:          ref("reference.html"),
			},
		})
	}
	out, err := yaml.Marshal(tests)
	if err != nil {
		return err
	}
	if err := os.WriteFile(testsPath, append([]byte(generatedHeader), out...), 0o644); err != nil {
		return fmt.Errorf("write tests: %w", err)
	}
	return nil
}
